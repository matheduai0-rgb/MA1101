#!/usr/bin/env python3
"""
list_components.py - regenerate references/component_catalog.md from components/*.vue.

For each component it reads the TypeScript props (defineProps<{...}>, inline or
multi-line), the first comment line if any, and which decks in 2026/slides/ use it.

Usage:
  python3 list_components.py            # rewrite references/component_catalog.md
  python3 list_components.py --stdout   # print instead
"""

import re
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
ROOT = next(p for p in SKILL.parents if (p / "AGENTS.md").exists())
COMPONENTS = ROOT / "components"
DECKS = ROOT / "2026" / "slides"


def props_of(src: str):
    m = re.search(r"defineProps<\{(.*?)\}>", src, re.S)
    if not m:
        m = re.search(r"defineProps\(\{(.*?)\}\)", src, re.S)
    if not m:
        return ""
    body = m.group(1)
    out = []
    for part in re.split(r"[;\n]", body):
        pm = re.match(r"\s*(\w+)\??\s*:\s*(.+?)\s*,?\s*$", part)
        if pm:
            typ = re.sub(r"\s+", " ", pm.group(2)).replace("|", "/")  # keep the Markdown table intact
            out.append(f"`{pm.group(1)}`: {typ}" if "'" in typ else f"`{pm.group(1)}`")
    return ", ".join(out)


def decks_using(name: str):
    hits = []
    for md in sorted(DECKS.glob("*/slides.md")):
        if re.search(rf"<{name}\b", md.read_text(encoding="utf-8", errors="ignore")):
            hits.append(md.parent.name)
    return hits


def main():
    rows = []
    for vue in sorted(COMPONENTS.glob("*.vue")):
        src = vue.read_text(encoding="utf-8", errors="ignore")
        decks = decks_using(vue.stem)
        shown = ", ".join(decks[-3:]) + (f" (+{len(decks) - 3} more)" if len(decks) > 3 else "")
        rows.append((vue.stem, props_of(src), shown or "—"))
    lines = [
        "# Component catalogue (generated)",
        "",
        "Generated by `scripts/list_components.py` from `components/*.vue`; rerun it after adding a",
        "component. Reuse one of these before writing a new applet; the deck column shows a working example.",
        "",
        "| component | props | used in decks |",
        "|---|---|---|",
    ]
    lines += [f"| `{n}` | {p or '—'} | {d} |" for n, p, d in rows]
    text = "\n".join(lines) + "\n"
    if "--stdout" in sys.argv:
        print(text)
    else:
        out = SKILL / "references" / "component_catalog.md"
        out.parent.mkdir(exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out} ({len(rows)} components)")


if __name__ == "__main__":
    main()
